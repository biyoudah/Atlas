using System.Text.Json.Serialization;
using Atlas.Serving;

namespace Atlas.Models;

/// <summary>
/// Fully normalized, protocol-complete canonical representation of an industrial signal.
/// Preserves complete signal provenance, timestamps, OPC UA status code, and data quality state.
/// Prevents collapsing null, stale, zero, and bad status codes into false metrics.
/// </summary>
public record CanonicalSignal
{
    /// <summary>
    /// Original OPC UA NodeId string.
    /// </summary>
    [JsonPropertyName("nodeId")]
    public required string NodeId { get; init; }

    /// <summary>
    /// Stable namespace-URI-based identifier (immune to server namespace table shifts).
    /// </summary>
    [JsonPropertyName("stableNodeId")]
    public string? StableNodeId { get; init; }

    /// <summary>
    /// Raw un-coerced value directly from OPC UA payload.
    /// </summary>
    [JsonPropertyName("rawValue")]
    public object? RawValue { get; init; }

    /// <summary>
    /// Numerically coerced double representation if measurable scalar; null otherwise.
    /// </summary>
    [JsonPropertyName("numericValue")]
    public double? NumericValue { get; init; }

    /// <summary>
    /// OPC UA DataType name (e.g. Double, Int32, Boolean, String, ExtensionObject).
    /// </summary>
    [JsonPropertyName("dataType")]
    public string? DataType { get; init; }

    /// <summary>
    /// Full 32-bit OPC UA status code representing data health.
    /// </summary>
    [JsonPropertyName("statusCode")]
    public uint StatusCode { get; init; } = StatusCodes.Good.Code;

    /// <summary>
    /// Processed quality state after hysteresis (Good, Uncertain, Bad).
    /// </summary>
    [JsonPropertyName("quality")]
    public QualityState Quality { get; init; } = QualityState.Good;

    /// <summary>
    /// Timestamp generated by the physical sensor or PLC clock (SourceTimestamp).
    /// </summary>
    [JsonPropertyName("sourceTimestampUtc")]
    public DateTime SourceTimestampUtc { get; init; } = DateTime.UtcNow;

    /// <summary>
    /// Timestamp assigned by the OPC UA server communication stack (ServerTimestamp).
    /// </summary>
    [JsonPropertyName("serverTimestampUtc")]
    public DateTime ServerTimestampUtc { get; init; } = DateTime.UtcNow;

    /// <summary>
    /// Arrival timestamp at the Atlas edge collector.
    /// </summary>
    [JsonPropertyName("receivedTimestampUtc")]
    public DateTime ReceivedTimestampUtc { get; init; } = DateTime.UtcNow;

    /// <summary>
    /// Whether this telemetry point is frozen/stale past the configured staleness threshold.
    /// </summary>
    [JsonPropertyName("isStale")]
    public bool IsStale { get; init; }

    /// <summary>
    /// Subscribed or configured sampling interval in milliseconds.
    /// </summary>
    [JsonPropertyName("samplingIntervalMs")]
    public double SamplingIntervalMs { get; init; } = 250.0;

    /// <summary>
    /// Standardized semantic metric label (e.g. spindle_speed, parts_produced).
    /// </summary>
    [JsonPropertyName("semanticLabel")]
    public string? SemanticLabel { get; init; }

    /// <summary>
    /// Physical engineering unit (e.g. rpm, mm/min, °C, bar, count, s).
    /// </summary>
    [JsonPropertyName("unit")]
    public string? Unit { get; init; }

    /// <summary>
    /// Origin tier of the semantic classification (Standard, Vendor, Custom, Heuristic).
    /// </summary>
    [JsonPropertyName("provenance")]
    public SignalProvenance Provenance { get; init; } = SignalProvenance.HeuristicInference;

    /// <summary>
    /// Semantic mapping confidence score (0.0 to 1.0).
    /// </summary>
    [JsonPropertyName("confidence")]
    public double Confidence { get; init; }

    /// <summary>
    /// MTConnect taxonomy classification category (Sample, Event, Condition).
    /// </summary>
    [JsonPropertyName("category")]
    public SignalCategory Category { get; init; } = SignalCategory.Sample;

    /// <summary>
    /// Raw controller state if discrete state node.
    /// </summary>
    [JsonPropertyName("rawState")]
    public string? RawState { get; init; }

    /// <summary>
    /// Standardized machine tool state preserving multi-state fidelity (e.g. Ready, Active, Interrupted, FeedHold).
    /// </summary>
    [JsonPropertyName("standardizedState")]
    public string? StandardizedState { get; init; }

    /// <summary>
    /// Associated static catalog metadata entry.
    /// </summary>
    [JsonIgnore]
    public CatalogEntry? Entry { get; init; }
}
